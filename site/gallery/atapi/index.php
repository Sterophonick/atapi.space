<h2 id="p1">Bio</h2>
<p>
Atapi (he/she/they) is an anthropomorphic shorthaired domestic cat, who appears as a self-insert character to my real-life self. He doesn't really have any dedicated lore of his own, as he is supposed to be just "me if I was a fuzzy cat."<br/><br/>

His name originates from <a href="https://en.wikipedia.org/wiki/ATAPI"><i>ATA Packet Interface</i></a>, which was a legacy standard used for sending SCSI commands to removable storage mediums such as CD-ROM, DVD, or LTO Tapes, primarily made for IBM PC-compatible machines. It's since fizzled out of use in favor of the much faster Serial ATA protocol, and much more recently, NVMe.<br/><br/>

He was originally created from a doodle I made one evening in November of 2020 because it was still the middle of lockdown and I had nothing to really do. There wasn't really much intent or thought in regards to the drawing, it just kinda came together as my hand led the way to drawing the little critter. Of course, because I'm me, the drawing was also done in <i>Mario Artist: Paint Studio</i> for the Nintendo 64DD.<br/>
<img width="512px" loading="lazy" src="/assets/img/gallery/atapi_ogdoodle.png"><br/><br/>

What little early (pre-June 2021) artwork exists depicts him having these odd Pikachu-like ears, in large part because I had no clue how to draw ears at the time and couldn't commission any artists to make anything. Sometimes it still happens if it fits the current bit.</p>

