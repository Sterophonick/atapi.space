<h2>Bomb Rush Cyberfunk</h2>
<p>
    Picture: <i>Jet Set Radio</i>, but if its controls didn't suck, and it was more awesomer.<br/><br/>

    <> screenshot of game, in the overworld or something <>

    <i>Bomb Rush Cyberfunk</i> is a 3D arcade-style skating game developed by Team Lizard. You, taking control of the character Red, must build up your own little graffiti crew and assert dominance over the 5 boroughs of New Amsterdam. Going All City, if you will. You do this by doing awesome boosts, doing awesome tricks and drawing awesome graffiti, much to the dismay of the increasingly militarized police force that will absolutely kill you because they are scum.<br/><br/>

    <> moar screenshots <>

    Jet Set Radio is not a very accessible game, I love it, but I hate playing it. Its controls and physics are so unbelievably out of whack that I ragequit before making much progress, especially at the halfway point. Which is why I'm so happy to say that this game <i>feels good</i>. It's responsive, the camera-relative movement gives you want you expect, and you're also given the aforementioned boost in order to correct your trajectory OR you can use it to chain trick combos and rack up some serious points, a thing that is required to progress the game.<br/><br/>

    All of this is wrapped up with an <i>infectiously</i> awesome electronic funk hip-hop fusion soundtrack, featuring artists such as 2 Mello, Charodey Jeddy, Hideki Naganuma, SkyBlew, as well as others, AND the awesome modernized cel-shaded Dreamcast aesthetic. If you're a fan of Y2K aesthetics, you probably already have this game.<br/><br/>

    Where to buy: <a href="https://store.steampowered.com/app/1353230/Bomb_Rush_Cyberfunk/">Steam</a>, also available on consoles<br/>
    Price: $39.99 USD, regularly drops down to $19.99 on Steam during sales.<br/>
    HLTB: ~8 Hours<br/><br/>
</p>

