        </li>
        <li>
            <yellow>Sugar</yellow> - Once again to take the bite out of those salty components.
        </li>
        <li>
            <yellow>Mirin</yellow> - Japanese rice wine. Adds some umami flavor to your protein.
        </li>
    </ul>
