    I don't use any fancy schmancy techniques or equipment or anything, besides a Wok. You can make some good fried rice with many ingredients that can be acquired here in the United States in your average household.
</p>

<br/>

<h2>Ingredients</h2>

<p>
    Nothing about these ingredients are really measured or anything. In truth, eyeballing it is a great way to go, as fried rice is a very, very flexible dish that was originally intended to use up whatever the hell was in the house.<br/><br/>

    To start, we are going to make a <light-blue>sauce mixture</light-blue>. You want to aim for roughly 4 tbsp or 60 mL of this stuff, containing the following ingredients:<br/><br/>
</p>

<div class="ingredients" style="width:60%; margin:auto; text-align: left;">
    <ul>
        <li>
            <yellow>Light Soy Sauce</yellow> - I always go for Lee Kum Kee or Pearl River Bridge brands of soy sauce for cooking. Kikkoman is a common culprit of a mid-tier fried rice, it doesn't really have as suitable of a flavor profile I feel. Lee Kum Kee brands this as "Premium Soy Sauce."
        </li>
        <li>
            <yellow>Dark Soy Sauce</yellow> - Ditto.
        </li>
        <li>
            <yellow>MSG</yellow> - A seasoning that's ubiquitous in Asian cooking.
        </li>
        <li>
            <yellow>Sugar</yellow> - Pure cane sugar. Used to take the bite out of the salty components.
        </li>
        <li>
            <yellow>Oyster Sauce</yellow>
        </li>
    </ul>
</div>

<br/>

<p>
    We're also gonna have a <light-blue>dry spice mixture</light-blue>. You're aiming for about half a tbsp (7.5g) total of stuff like this:<br/><br/>
</p>

<div class="ingredients" style="width:60%; margin:auto; text-align: left;">
    <ul>
        <li>
            <yellow>Kosher Salt</yellow> - Because of course.
        </li>
        <li>
            <yellow>Pepper</yellow> - I prefer doing this with white pepper but black also works.
        </li>
        <li>
            <yellow>Garlic Powder</yellow> - What's a dish without garlic, right?
        </li>
        <li>
            <yellow>MSG</yellow> - More MSG cannot hurt, right?
        </li>
        <li>
            <yellow>Sugar</yellow> - yeah.
        </li>
    </ul>
</div>

<br/>

<p>
    Your proteins of choice are ideally going to be marinated for at least 24 hours in something like this, and I have tried this with chicken breast and pork belly. You don't need much of any of these ingredients, just enough to lightly-ish coat the surface is perfectly cromulent:
</p>

<div class="ingredients" style="width:60%; margin:auto; text-align: left;">
    <ul>
        <li>
            <yellow>Baking Soda</yellow> - This is to alkalize the meat and ensure that it remains tender and the proteins don't tense up so much once it comes time to fry. Do this first.
        </li>
        <li>
            <yellow>Canola Oil</yellow> - Do this after the baking soda so the other seasonings bind better.
        </li>
        <li>
            <yellow>Light Soy Sauce</yellow>
        </li>
        <li>
            <yellow>Kosher Salt</yellow>
        </li>
        <li>
            <yellow>MSG</yellow>
        </li>
        <li>
            <yellow>Sugar</yellow> - Once again to take the bite out of those salty components.
        </li>
        <li>
            <yellow>Mirin</yellow> - Japanese rice wine. Adds some umami flavor to your protein.
        </li>
    </ul>
</div>

<br/>

<p>
    You're of course going to want other tasty things in there. Here's some things I like to do:
</p>

<div class="ingredients" style="width:60%; margin:auto; text-align: left;">
    <ul>
        <li>
            <yellow>Eggs</yellow> - I always season these with MSG and scramble them right before it's time to cook. Assmebly instructions will contain a step for eggs.
        </li>
        <li>
            <yellow>Vegetables</yellow> - Carrots, sweet onion, celery, corn and peas are ones I like to do. Some bean sprouts would also be good.
        </li>
        <li>
            <yellow>Minced Garlic</yellow> - Because reasons. Assembly instructions have this as well.
        </li>
        <li>
            <yellow>Shaoxing Wine (Optional)</yellow> - Extremely common in Chinese cooking. Helps brighten up much of the flavors but can be tricky to add and ensure all the alcohol is cooked off.
        </li>
        <li>
            <yellow>Toasted Sesame Oil</yellow> - It's just good, and the fact that it's toasted means we get a hint of that slightly charred flavor we get from takeout because restaurants use those decommissioned jet engine-type burners.
        </li>
    </ul>
</div>

<p>
    Of course, you're gonna want some rice. While it's true that the rice can matter if you're really pedantic, it honestly doesn't if you're just wanting to make something good at home to share with friends. In my household we use <yellow>Jasmine Rice</yellow> but there are some brands that have made dedicated blends for fried rice, typically containing American Long Grain white rice and Jasmine.<br/>
